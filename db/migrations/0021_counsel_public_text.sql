comment on column public.counseling_notes.public_text is
  '학부모·학생에게 보이는 **확정** 공개 문장. 강사가 화면에서 확인·수정하고 저장한 값이다. '
  'ai_draft.student_safe_text 는 AI 가 만든 미확정 초안이고 이 컬럼은 강사가 확정한 값이라는 점에서 다르다 — '
  '초안이 이 컬럼으로 자동으로 들어오는 경로는 없다(강사가 [공개용 문장 가져오기] 로 폼에 채우고 다시 저장해야 한다). '
  '비어 있으면 학부모·학생 화면은 종전처럼 content 를 보여준다(폴백). 과거 행을 백필하지 않는다. '
