-- ═══════════════════════════════════════════════════════════════════
--
--  0021_counsel_public_text
--
--  목적
--    상담 기록을 학부모에게 보일 때 **강사가 확정한 문장**을 따로 담는다.
--
--    지금까지 학부모 화면은 상담 기록의 content(강사가 쓴 확정 내용)를 그대로 썼다.
--    content 는 강사가 자기 관리용으로 적는 자리라, 제3자 언급이나 학생이 없는
--    자리에서 오간 평가가 섞일 수 있다. 그렇다고 AI 가 만든 문장
--    (ai_draft.student_safe_text)을 그대로 내보낼 수도 없다 — 그건 초안이다.
--    그래서 **강사가 확인·수정해 확정한 공개용 문장**을 담을 자리를 하나 만든다.
--
--  ★ public_text 와 ai_draft.student_safe_text 의 구분 (이 마이그레이션의 핵심)
--    · ai_draft.student_safe_text
--        AI 가 전사문을 읽고 만든 **미확정 초안**이다. 강사가 본 적 없을 수 있다.
--        학생·학부모 조회 화이트리스트(js/db.js COUNSEL_SAFE_COLS)에 **넣지 않는다.**
--        서버(api/counsel-draft.js)에도 이 값이 확정 필드로 가는 경로가 없다.
--    · public_text  ← 이 컬럼
--        강사가 화면의 [학부모·학생 공개용 문장] 칸에서 확인·수정하고 [저장] 을
--        눌러 **확정한 값**이다. 그래서 학생·학부모에게 나가도 된다.
--        초안에서 이 칸으로 오는 유일한 길은 강사가 [공개용 문장 가져오기] 를 눌러
--        폼에 채우고 다시 저장하는 2단계뿐이다(Phase 6 이래의 원칙).
--
--  ★ 비어 있어도 된다 — 폴백이 있다
--    public_text 가 null 이거나 빈 문자열이면 학부모·학생 화면은 종전처럼 content 를
--    보여 준다. 지금까지 쌓인 상담 기록에는 이 컬럼이 비어 있으므로, 폴백이 없으면
--    공개 표시된 과거 상담이 화면에서 통째로 사라진다. 백필하지 않는다.
--
--  ★ 노출 게이트는 이 컬럼이 아니라 visible_to_student 다
--    public_text 를 채웠다고 공개되는 것이 아니다. 강사가 [학생·학부모에게 공개] 를
--    체크한 행만 나간다(RLS 0006 stu_self 도 같은 조건을 건다).
--
--  ★★ 데이터 보존 — 이 파일은 기존 행을 단 하나도 건드리지 않는다 ★★
--    · 컬럼 하나를 더할 뿐이다. update / drop / truncate / delete 없음.
--    · 기존 컬럼(content·follow_up·ai_draft·transcript)의 의미를 바꾸지 않는다.
--    · RLS 정책을 손대지 않는다 — counseling_notes 의 stu_self(0006)는 **행 단위**라
--      컬럼이 늘어도 정책이 달라질 것이 없다. 컬럼을 가리는 일은 종전과 같이
--      조회 화이트리스트(js/db.js COUNSEL_SAFE_COLS)가 맡는다.
--
